/**
 * Translate a phrase into the target language code.
 * Falls back to English if no translation is available or if target is 'en'.
 */
export function getTradeSnapText(text, targetLang = 'en') {
    if (!text || typeof text !== 'string') return text || '';
    const lang = (targetLang || 'en').toLowerCase();
    if (lang === 'en') return text;

    // 1. Direct match in main static dictionary
    const entry = TRADESNAP_TRANSLATIONS[text];
    if (entry && entry[lang]) {
        return entry[lang];
    }

    // 2. Direct match in dynamic dictionary
    const dynEntry = TRADESNAP_DYNAMIC_DICTIONARY[text];
    if (dynEntry && dynEntry[lang]) {
        return dynEntry[lang];
    }

    // 3. Trimmed check in both dictionaries
    const trimmed = text.trim();
    const entryTrimmed = TRADESNAP_TRANSLATIONS[trimmed] || TRADESNAP_DYNAMIC_DICTIONARY[trimmed];
    if (entryTrimmed && entryTrimmed[lang]) {
        return entryTrimmed[lang];
    }

    // 4. Pattern / Regex matchers
    const patternMatched = matchDynamicTradeSnapText(trimmed, lang);
    if (patternMatched) {
        return patternMatched;
    }

    return text;
}
